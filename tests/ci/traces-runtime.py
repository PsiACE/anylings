def free_port():
    with socket.socket() as sock:
        sock.bind(("127.0.0.1", 0))
        return sock.getsockname()[1]


class Owned:
    def __init__(self, command, log_path):
        self.log = log_path.open("w")
        self.child = subprocess.Popen(command, stdout=self.log, stderr=self.log)
        self.name = Path(command[0]).name

    def stop(self):
        if self.child.poll() is None:
            self.child.terminate()
        try:
            self.child.wait(timeout=40)
        except subprocess.TimeoutExpired:
            self.child.kill()
            self.child.wait(timeout=10)
        self.log.close()
        assert self.child.poll() is not None, f"{self.name} did not terminate"


def wait_http(url, owned, timeout=60):
    deadline = time.monotonic() + timeout
    while time.monotonic() < deadline:
        for item in owned:
            assert item.child.poll() is None, f"{item.name} exited; see its log"
        try:
            with urlopen(url, timeout=2):
                return
        except (URLError, HTTPError, TimeoutError, ConnectionError):
            time.sleep(0.3)
    raise AssertionError(f"{url} did not become available")


def string(value):
    return {"stringValue": value}


def spans_payload():
    """One trace: a legitimate server span plus a hostile canary for every
    caller-controlled surface the slice retains or must remove."""
    now = time.time_ns()
    root_id, child_id = "aaaaaaaaaaaaaaaa", "bbbbbbbbbbbbbbbb"
    probe_id, canary_id = "cccccccccccccccc", "dddddddddddddddd"
    trace_id = "4bf92f3577b34da6a3ce929d0e0e4736"

    def span(span_id, parent, name, start, end, status, attributes, kind=2,
             events=None):
        record = {
            "traceId": trace_id,
            "spanId": span_id,
            "name": name,
            "kind": kind,
            "startTimeUnixNano": str(start),
            "endTimeUnixNano": str(end),
            "status": status,
            "attributes": [
                {"key": key, "value": value}
                for key, value in attributes.items()
            ],
        }
        if parent:
            record["parentSpanId"] = parent
        if events:
            record["events"] = events
        return record

    return {
        "resourceSpans": [{
            "resource": {"attributes": [
                {"key": "service.name", "value": string("checkout-api")},
                *[
                    {"key": key, "value": string(value)}
                    for key, value in HOSTILE_RESOURCE_ATTRIBUTES.items()
                ],
            ]},
            "scopeSpans": [{
                "scope": {
                    "name": HOSTILE_SCOPE["name"],
                    "version": "1.0",
                    "attributes": [
                        {"key": "scope.leak",
                         "value": string(HOSTILE_SCOPE["attribute"])}
                    ],
                },
                "spans": [
                    # Legitimate control: must be stored with its context.
                    span(root_id, None, "GET /checkout", now - 4_000_000, now,
                         {"code": 1},
                         {"http.request.method": string("GET"),
                          "http.route": string("/checkout"),
                          "http.response.status_code": {"intValue": "200"},
                          **{key: string(value)
                             for key, value in HOSTILE_SPAN_ATTRIBUTES.items()}}),
                    span(child_id, root_id, "SELECT cart", now - 2_500_000,
                         now - 1_000_000, {"code": 2, "message": "timeout"},
                         {"error.type": string("timeout"),
                          "rpc.method": string("Cart.Get")}),
                    # A route template is a legitimate default span name and
                    # must survive: the contract is bounded, not maximally narrow.
                    span(probe_id, root_id, "/checkout/{cartId}",
                         now - 2_000_000, now - 1_500_000, {"code": 1},
                         {"http.route": string("/checkout/{cartId}")}),
                    # W3C trace state on a kept span: it must be cleared.
                    span("6666666666666666", root_id, "TRACESTATE", now - 2_200_000,
                         now - 1_800_000, {"code": 1}, {}) | {"traceState": HOSTILE_TRACE_STATE},
                    # A span carrying a link is rejected whole: this release has
                    # no link context, and the store's LogSQL projection would
                    # otherwise keep the link attributes.
                    {**span("7777777777777777", root_id, "LINKPROBE",
                            now - 2_100_000, now - 1_700_000, {"code": 1}, {}),
                     "links": [{
                         "traceId": "bbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbb",
                         "spanId": "cccccccccccccccc",
                         "traceState": HOSTILE_LINK["trace_state"],
                         "attributes": [
                             {"key": "authorization",
                              "value": string(HOSTILE_LINK["credential"])},
                             {"key": "link.note", "value": string(HOSTILE_LINK["note"])},
                         ],
                     }]},
                    # Query strings are not operation identifiers.
                    span("8888888888888888", root_id, HOSTILE_NAME_QUERY,
                         now - 1_900_000, now - 1_600_000, {"code": 1},
                         {"http.route": string(HOSTILE_ROUTE_QUERY)}),
                    # A credential smuggled through an ALLOWED key. Key
                    # filtering alone would keep the key, so the value contract
                    # must reject this span; it is not expected to be stored.
                    span("eeeeeeeeeeeeeeee", root_id, "SMUGGLED", now - 800_000,
                         now - 400_000, {"code": 1},
                         {"http.request.method": string(HOSTILE_ALLOWED_KEY_VALUE)}),
                    # Canary: an event with a hostile name and attribute, plus
                    # a hostile status message. The span must survive with both
                    # neutralised, not be deleted.
                    span(canary_id, root_id, "CANARY", now - 1_000_000, now,
                         {"code": 2, "message": HOSTILE_STATUS_MESSAGE},
                         {},
                         events=[{
                             "timeUnixNano": str(now),
                             "name": HOSTILE_EVENT["name"],
                             "attributes": [{
                                 "key": "exception.message",
                                 "value": string(HOSTILE_EVENT["attribute"]),
                             }],
                         }]),
                ],
            }],
        }, {
            # A second resource carries hostile values for the retained
            # resource keys, and repeats keys so the FIRST occurrence is valid
            # and the SECOND is hostile. `attributes[...]` reads the first, so
            # an in-place check would pass while the exporter and store keep
            # both -- which is exactly the bypass the canonical rebuild fixes.
            # These are real duplicate entries in the wire list, not a collapsed
            # dict.
            "resource": {"attributes": [
                {"key": "service.name", "value": string("bad-resource-api")},
                {"key": "service.name",
                 "value": string(HOSTILE_RESOURCE_VALUES["service.name"])},
                {"key": "k8s.namespace.name", "value": string("agents")},
                {"key": "k8s.namespace.name",
                 "value": string(HOSTILE_RESOURCE_VALUES["k8s.namespace.name"])},
                {"key": "deployment.environment.name", "value": string("dev")},
                {"key": "deployment.environment.name",
                 "value": string(f"Bearer {HOSTILE}-ENVCRED")},
            ]},
            "scopeSpans": [{"spans": [{
                "traceId": trace_id,
                "spanId": "9999999999999999",
                "name": "DUPROUTE",
                "kind": 2,
                "startTimeUnixNano": str(now - 900_000),
                "endTimeUnixNano": str(now - 500_000),
                "status": {"code": 1},
                # Duplicate `http.route`: valid first, query-string second.
                "attributes": [
                    {"key": "http.route", "value": string("/dup")},
                    {"key": "http.route",
                     "value": string(f"/dup?x={HOSTILE}-DUPROUTE")},
                    {"key": "http.request.method", "value": string("GET")},
                    {"key": "http.request.method",
                     "value": string(f"Bearer {HOSTILE}-DUP-METHOD")},
                ],
            }]}],
        }],
    }


def query_traces(base, service):
    """Jaeger-compatible lookup. The window is in MICROseconds in v0.13.0."""
    now_us = time.time_ns() // 1000
    query = urlencode({
        "service": service,
        "limit": 5,
        "start": now_us - 3_600_000_000,
        "end": now_us + 60_000_000,
    })
    with urlopen(f"{base}/select/jaeger/api/traces?{query}", timeout=10) as response:
        return json.load(response)


def run(scratch):
    store_binary = os.environ["VICTORIA_TRACES_BIN"]
    collector_binary = os.environ["OTELCOL_BIN"]
    assert "v0.13.0" in subprocess.check_output(
        [store_binary, "--version"], text=True, timeout=20
    ), "the trace store is not the pinned v0.13.0 release"

    # 1. The rendered configuration, unmodified, through the pinned parser.
    rendered_yaml = scratch / "rendered-events-collector.yaml"
    assert rendered_yaml.is_file(), "the rendered collector config was not captured"
    env = {**os.environ, "MY_POD_IP": "127.0.0.1"}
    with (scratch / "traces-rendered-validate.log").open("w") as log:
        subprocess.run([collector_binary, "validate", f"--config={rendered_yaml}"],
                       env=env, stdout=log, stderr=log, check=True, timeout=30)
    print("[observability] runtime: unmodified rendered collector config accepts the trace pipeline")

    relay = json.loads((scratch / "rendered-events-collector.json").read_text())
    assert "traces" in relay["service"]["pipelines"], "the render has no traces pipeline"
    pipeline = relay["service"]["pipelines"]["traces"]
    assert pipeline["exporters"] == ["otlphttp/victoria-traces"], pipeline
    # The trace path must not share the log exporter: a span cannot be stored as
    # a log line, and this is enforced rather than assumed.
    assert "otlphttp/victoria-logs" not in pipeline["exporters"], pipeline
    assert "filter/traces_privacy" in pipeline["processors"], pipeline
    assert "transform/traces_privacy" in pipeline["processors"], pipeline

    store_port, otlp_port, metrics_port, health_port = (
        free_port(), free_port(), free_port(), free_port()
    )
    data = scratch / "victoria-traces-data"
    shutil.rmtree(data, ignore_errors=True)

    # 2. Only addresses move; every rendered flag, including the memory budget
    #    and retention, is passed through unchanged.
    store_args = [
        f"-storageDataPath={data}",
        f"-httpListenAddr=127.0.0.1:{store_port}",
        "-retentionPeriod=7d",
    ]
    rendered_store = scratch / "victoria-traces.yaml"
    if rendered_store.is_file():
        documents = [
            document for document in yaml.safe_load_all(rendered_store.read_text())
            if document
        ]
        deployment = next(d for d in documents if d.get("kind") == "Deployment")
        args = deployment["spec"]["template"]["spec"]["containers"][0]["args"]
        assert "--retentionPeriod=7d" in args, args
        store_args = [
            arg for arg in args
            if arg.lstrip("-").split("=", 1)[0] not in ("storageDataPath", "httpListenAddr")
        ] + [f"-storageDataPath={data}", f"-httpListenAddr=127.0.0.1:{store_port}"]

    store = Owned([store_binary, *store_args], scratch / "victoria-traces.log")
    children = [store]
    try:
        wait_http(f"http://127.0.0.1:{store_port}/health", children)

        relay["extensions"]["health_check"]["endpoint"] = f"127.0.0.1:{health_port}"
        relay["receivers"]["otlp"]["protocols"]["http"]["endpoint"] = f"127.0.0.1:{otlp_port}"
        relay["exporters"]["otlphttp/victoria-traces"]["traces_endpoint"] = (
            f"http://127.0.0.1:{store_port}/insert/opentelemetry/v1/traces"
        )
        # The log pipeline is out of scope here and its store is not running.
        relay["service"]["pipelines"].pop("logs/events", None)
        relay["service"]["pipelines"].pop("logs/structured", None)
        relay["receivers"].pop("k8sobjects", None)
        relay["service"]["telemetry"]["metrics"]["readers"] = [{
            "pull": {"exporter": {"prometheus": {"host": "127.0.0.1", "port": metrics_port}}}
        }]
        config = scratch / "traces-collector.json"
        config.write_text(json.dumps(relay, indent=2))
        with (scratch / "traces-collector-validate.log").open("w") as log:
            subprocess.run([collector_binary, "validate", f"--config={config}"],
                           env=env, stdout=log, stderr=log, check=True, timeout=30)
        collector = Owned([collector_binary, f"--config={config}"],
                          scratch / "traces-collector.log")
        children.append(collector)
        try:
            wait_http(f"http://127.0.0.1:{metrics_port}/metrics", children)

            payload = spans_payload()
            # Payload-presence guard. A canary that is listed and scanned but
            # never emitted makes the scan pass vacuously -- exactly how the
            # resource-value canaries went untested before. So every scanned
            # canary must appear in the wire payload.
            wire = json.dumps(payload)
            for marker in ALL_CANARIES:
                assert marker in wire, ("canary never emitted", marker)
            # Duplicate keys must be real repeats in the OTLP attribute lists,
            # not a collapsed mapping: the bypass is about ordering.
            key_lists = []
            for resource in payload["resourceSpans"]:
                key_lists.append([a["key"] for a in resource["resource"]["attributes"]])
                for scope in resource["scopeSpans"]:
                    for span in scope["spans"]:
                        key_lists.append([a["key"] for a in span["attributes"]])
            assert any(len(keys) != len(set(keys)) for keys in key_lists), (
                "the payload carries no duplicate attribute key, so the "
                "duplicate-order regression cannot fail")
            request = Request(
                f"http://127.0.0.1:{otlp_port}/v1/traces",
                data=json.dumps(payload).encode(),
                headers={"Content-Type": "application/json"},
            )
            with urlopen(request, timeout=10) as response:
                assert response.status == 200, response.status

            base = f"http://127.0.0.1:{store_port}"
            deadline = time.monotonic() + 45
            traces = []
            while time.monotonic() < deadline:
                assert all(child.child.poll() is None for child in children), (
                    "a runtime service exited; see its log")
                try:
                    traces = query_traces(base, "checkout-api").get("data") or []
                except (URLError, TimeoutError, ConnectionError, HTTPError):
                    traces = []
                if traces:
                    break
                time.sleep(1)
            else:
                raise AssertionError("the trace store returned no trace for checkout-api")

            # 3. A real trace, with real parenting and durations, and the
            # legitimate route-template name retained (the contract is bounded,
            # not maximally narrow).
            spans = {span["operationName"]: span for span in traces[0]["spans"]}
            # DUPROUTE is the duplicate-key control: it is stored like any
            # other span, and the point is that its hostile second occurrences
            # do not survive.
            assert set(spans) == {
                "GET /checkout", "SELECT cart", "/checkout/{cartId}", "CANARY",
                "TRACESTATE", "DUPROUTE",
            }, spans.keys()
            # The duplicate span keeps exactly one route, the valid one.
            assert [tag["value"] for tag in spans["DUPROUTE"]["tags"]
                    if tag["key"] == "http.route"] == ["/dup"], spans["DUPROUTE"]["tags"]
            # A span carrying a link is rejected whole, so it and its hostile
            # link attributes never reach either projection.
            assert "LINKPROBE" not in spans, spans.keys()
            # `Len(links) > 0` must have dropped something, or the link rule is
            # not actually running.
            metrics = urlopen(
                f"http://127.0.0.1:{metrics_port}/metrics", timeout=10).read().decode()
            filtered = sum(
                float(line.rsplit(" ", 1)[1]) for line in metrics.splitlines()
                if line.startswith("otelcol_processor_filter_spans_filtered_total{")
            )
            # name-query, query-route, allowed-key credential, link span, and the
            # resource-value span is filtered by resource attributes.
            assert filtered >= 3, filtered
            root, child = spans["GET /checkout"], spans["SELECT cart"]
            assert root["duration"] > 0 and child["duration"] > 0, (root, child)
            assert child["references"], "the child span lost its parent reference"
            parent = child["references"][0]
            assert parent["spanID"] == root["spanID"], (parent, root["spanID"])
            assert parent["traceID"] == root["traceID"] == traces[0].get(
                "traceID", parent["traceID"]), parent
            # The failing child carries its error status through to the store.
            tags = {tag["key"]: tag["value"] for tag in child["tags"]}
            assert tags.get("error.type") == "timeout", tags
            root_tags = {tag["key"]: tag["value"] for tag in root["tags"]}
            assert root_tags.get("http.response.status_code") == "200", root_tags

            # 4. Privacy: every caller-controlled surface is checked against the
            # whole stored response, not a grep of one field. The surfaces are
            # span attributes, span events (name and attributes), the
            # instrumentation scope (name and attributes), the status message,
            # the resource attributes, and a credential placed in an *allowed*
            # key -- which key filtering alone would not catch.
            # BOTH projections are scanned. The Jaeger API is a view: this
            # store also keeps its own LogSQL projection, which is where link
            # attributes and span trace state were found to survive even when
            # Jaeger omitted them. Scanning only the view would pass on a real
            # leak.
            jaeger_projection = json.dumps(traces)
            with urlopen(
                f"{base}/select/logsql/query?{urlencode({'query': '*', 'limit': 200})}",
                timeout=10,
            ) as response:
                logsql_projection = response.read().decode()
            assert logsql_projection.strip(), "the store's LogSQL projection was empty"
            assert "GET /checkout" in logsql_projection, (
                "the LogSQL projection does not contain the stored span, so a "
                "clean scan would prove nothing")
            stored = jaeger_projection + logsql_projection
            for marker in ALL_CANARIES:
                assert marker not in jaeger_projection, ("jaeger", marker)
                assert marker not in logsql_projection, ("logsql", marker)
            for marker in HOSTILE_SPAN_ATTRIBUTES.values():
                assert marker not in stored, marker
            for marker in HOSTILE_RESOURCE_ATTRIBUTES.values():
                assert marker not in stored, marker
            for forbidden in ("authorization", "session.id", "prompt", "tool.output",
                              "cookie", "host.name"):
                assert forbidden not in stored, forbidden
            # Only allowlisted span attributes are present, plus the tags the
            # store itself derives.
            # Tags the STORE derives from the span itself, not from a caller
            # attribute: the span kind, an error boolean, and (for a failing
            # span) a status description.
            # `otel.scope.name`/`otel.scope.version` are the fixed values the
            # collector writes (see transform/traces_privacy), not caller text.
            derived = {"span.kind", "error", "otel.status_description",
                       "otel.scope.name", "otel.scope.version"}
            every_tag = [tag for span in spans.values() for tag in span["tags"]]
            unexpected = {tag["key"] for tag in every_tag} - ALLOWED_SPAN_ATTRIBUTES - derived
            assert not unexpected, unexpected
            # The canary span keeps its event, but neutrally: the name is
            # replaced and its fields are empty. An event that still carried a
            # caller name or field would fail the canary scan above, so this
            # asserts the span was not simply deleted instead.
            canary = spans["CANARY"]
            assert canary["logs"], "the canary span lost its event entirely"
            for event in canary["logs"]:
                for field in event.get("fields") or []:
                    assert field["key"] in {"event"}, field
                    assert field["value"] == "event", field
            # A log record is not a span: the trace store must not have been fed
            # the log pipeline's output, and the fixture never posts logs here.

            (scratch / "trace-query.json").write_text(json.dumps(traces, indent=2))
            print(
                "[observability] runtime: workload span -> otel-events -> "
                "VictoriaTraces v0.13.0 -> Jaeger query; one trace with "
                f"{len(spans)} spans, child references root, error path intact, "
                "no caller credential/session/prompt/tool/host field stored"
            )
        finally:
            collector.stop()
    finally:
        store.stop()
    assert all(child.child.poll() is not None for child in children)
    print("[observability] runtime: trace store and collector terminated and waited")


if __name__ == "__main__":
    def terminate(_signum, _frame):
        raise SystemExit("runtime fixture terminated")

    signal.signal(signal.SIGTERM, terminate)
    scratch = Path(sys.argv[1])
    try:
        run(scratch)
    finally:
        if destination := os.environ.get("OBSERVABILITY_RUNTIME_LOG_DIR"):
            target = Path(destination)
            target.mkdir(parents=True, exist_ok=True)
            for path in [*scratch.glob("traces-*.log"), scratch / "trace-query.json"]:
                if path.is_file():
                    shutil.copy2(path, target / path.name)
