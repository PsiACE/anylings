"""Disposable runtime fixture for the request-trace slice.

Invoked only by check-observability.sh --runtime. It proves the actual path,
with the pinned binaries and no synthetic shortcut:

    workload -> OTLP/HTTP :4318 -> otel-events (filter + shape) ->
    VictoriaTraces -> Jaeger-compatible query

What that establishes, precisely:

* A **real trace** is ingested and retrieved: two spans of one trace, a root and
  a child that references the root, with durations, so parent/correlation is
  read back from the store rather than asserted on a static document.
* The span attributes that survive are exactly the allowlisted ones. Caller
  fields that look like a credential, a session, a prompt or tool output are
  absent from both the stored spans and the query response.
* The rendered collector configuration is validated by the pinned parser
  **before** any address substitution.

What it does NOT establish: that a live Kubernetes workload produced these
spans. The spans are generated by this fixture over loopback. Nothing here
touches a cluster, and no conclusion about production request rates or latency
follows from it.
"""

